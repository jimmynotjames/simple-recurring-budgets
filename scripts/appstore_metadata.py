#!/usr/bin/env python3
"""Validate and stage App Store metadata without network access.

Localized files in ``fastlane/metadata/<locale>/`` override the American
English source one field at a time. ``prepare`` expands those overrides into a
complete Fastlane metadata tree for every supported listing locale.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = REPO_ROOT / "fastlane" / "metadata"
DEFAULT_LOCALES = REPO_ROOT / "fastlane" / "metadata-locales.json"
DEFAULT_OUTPUT = REPO_ROOT / "tmp" / "appstore-metadata"
SAFE_OUTPUT_ROOT = REPO_ROOT / "tmp"
STAGING_MARKER = ".appstore-metadata-stage"
STAGING_MARKER_CONTENT = "Generated by scripts/appstore_metadata.py prepare.\n"

# Fastlane 2.242.0, FastlaneCore::Languages::ALL_LANGUAGES. These are App
# Store listing locales, not storefront country or region codes.
FASTLANE_LOCALES = (
    "ar-SA", "bn-BD", "ca", "cs", "da", "de-DE", "el", "en-AU",
    "en-CA", "en-GB", "en-US", "es-ES", "es-MX", "fi", "fr-CA",
    "fr-FR", "gu-IN", "he", "hi", "hr", "hu", "id", "it", "ja",
    "kn-IN", "ko", "ml-IN", "mr-IN", "ms", "nl-NL", "no", "or-IN",
    "pa-IN", "pl", "pt-BR", "pt-PT", "ro", "ru", "sk", "sl-SI",
    "sv", "ta-IN", "te-IN", "th", "tr", "uk", "ur-PK", "vi",
    "zh-Hans", "zh-Hant",
)


@dataclass(frozen=True)
class Field:
    filename: str
    required: bool = False
    max_characters: int | None = None
    max_utf8_bytes: int | None = None
    url: bool = False
    min_characters: int | None = None


# Limits come from Apple's App Store Connect Help pages for App Information and
# Platform Version Information. Apple documents keywords in UTF-8 bytes.
FIELDS = (
    Field("name.txt", required=True, min_characters=2, max_characters=30),
    Field("subtitle.txt", max_characters=30),
    Field("description.txt", required=True, max_characters=4000),
    Field("keywords.txt", required=True, max_utf8_bytes=100),
    Field("support_url.txt", required=True, url=True),
    Field("marketing_url.txt", url=True),
    Field("promotional_text.txt", max_characters=170),
    Field("release_notes.txt", required=True, max_characters=4000),
    Field("privacy_url.txt", required=True, url=True),
)
FIELD_BY_FILENAME = {field.filename: field for field in FIELDS}
# App-level files deliver reads from the metadata root; copyright.txt is the one every app needs.
ROOT_FILES = {
    "copyright.txt",
    "primary_category.txt",
    "secondary_category.txt",
    "primary_first_sub_category.txt",
    "primary_second_sub_category.txt",
    "secondary_first_sub_category.txt",
    "secondary_second_sub_category.txt",
}


class MetadataError(Exception):
    """A local metadata contract violation."""


def _read_text(path: Path) -> str:
    try:
        value = path.read_text(encoding="utf-8")
    except UnicodeDecodeError as error:
        raise MetadataError(f"{path}: must be valid UTF-8") from error
    except OSError as error:
        raise MetadataError(f"{path}: cannot be read: {error}") from error
    if not value.strip():
        raise MetadataError(
            f"{path}: explicit empty values are not allowed; remove an optional file instead"
        )
    return value


def _validate_url(path: Path, value: str) -> None:
    if any(character.isspace() for character in value):
        raise MetadataError(f"{path}: URL must not contain whitespace")
    try:
        parsed = urlsplit(value)
        hostname = parsed.hostname
        parsed.port  # Force validation of a malformed port.
    except ValueError as error:
        raise MetadataError(f"{path}: invalid URL: {error}") from error
    if parsed.scheme not in {"http", "https"} or not hostname:
        raise MetadataError(f"{path}: URL must be a complete http:// or https:// URL")


def _validate_copyright(path: Path, value: str) -> None:
    """Require a four-digit year, or a year range, followed by the owner name.

    A range is what a relicensing leaves behind ("2019-2026 Jimmy Ho"), so it is
    accepted; a reversed one is a typo rather than a style, so it is not.
    """
    match = re.fullmatch(r"(?P<start>\d{4})(?:-(?P<end>\d{4}))?\s+\S(?:.*\S)?", value)
    if not match:
        raise MetadataError(
            f"{path}: copyright must start with a four-digit year, or a "
            f"hyphenated range of two, followed by the owner name"
        )
    end = match.group("end")
    if end is not None and int(end) < int(match.group("start")):
        raise MetadataError(
            f"{path}: copyright year range ends before it starts: {match.group('start')}-{end}"
        )


def _validate_field(path: Path, field: Field) -> str:
    raw_value = _read_text(path)
    # Deliver strips values immediately before uploading. Validate the same
    # representation so a conventional trailing newline does not consume a
    # character or make an otherwise valid URL fail.
    value = raw_value.strip()
    if field.min_characters is not None and len(value) < field.min_characters:
        raise MetadataError(
            f"{path}: must contain at least {field.min_characters} characters"
        )
    if field.max_characters is not None and len(value) > field.max_characters:
        raise MetadataError(
            f"{path}: {len(value)} characters exceeds the {field.max_characters}-character limit"
        )
    byte_count = len(value.encode("utf-8"))
    if field.max_utf8_bytes is not None and byte_count > field.max_utf8_bytes:
        raise MetadataError(
            f"{path}: {byte_count} UTF-8 bytes exceeds the {field.max_utf8_bytes}-byte limit"
        )
    if field.url:
        _validate_url(path, value)
    return raw_value


def load_locale_manifest(path: Path) -> tuple[str, tuple[str, ...]]:
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise MetadataError(f"{path}: invalid locale manifest: {error}") from error
    if not isinstance(document, dict) or set(document) != {
        "fallback_locale", "locales", "source"
    }:
        raise MetadataError(
            f"{path}: expected only fallback_locale, locales, and source keys"
        )
    fallback = document["fallback_locale"]
    locales = document["locales"]
    source = document["source"]
    if not isinstance(fallback, str) or not isinstance(source, str) or not source.strip():
        raise MetadataError(f"{path}: fallback_locale and source must be non-empty strings")
    if not isinstance(locales, list) or not all(isinstance(item, str) for item in locales):
        raise MetadataError(f"{path}: locales must be an array of strings")
    if len(locales) != len(set(locales)):
        raise MetadataError(f"{path}: locales contains duplicates")
    unknown = sorted(set(locales) - set(FASTLANE_LOCALES))
    missing = sorted(set(FASTLANE_LOCALES) - set(locales))
    if unknown or missing:
        details = []
        if unknown:
            details.append(f"unsupported: {', '.join(unknown)}")
        if missing:
            details.append(f"missing: {', '.join(missing)}")
        raise MetadataError(f"{path}: locale list differs from Fastlane ({'; '.join(details)})")
    if fallback not in locales:
        raise MetadataError(f"{path}: fallback locale {fallback!r} is not in locales")
    return fallback, tuple(locales)


def _validate_source_shape(source: Path, locales: tuple[str, ...]) -> None:
    if not source.is_dir():
        raise MetadataError(f"{source}: metadata source directory is missing")
    allowed_locales = set(locales)
    for entry in source.iterdir():
        if entry.name in ROOT_FILES:
            if not entry.is_file() or entry.is_symlink():
                raise MetadataError(f"{entry}: must be a regular file")
            continue
        if entry.name not in allowed_locales:
            raise MetadataError(f"{entry}: unknown metadata entry")
        if not entry.is_dir() or entry.is_symlink():
            raise MetadataError(f"{entry}: locale entry must be a regular directory")
        for child in entry.iterdir():
            if child.name not in FIELD_BY_FILENAME:
                raise MetadataError(f"{child}: unknown metadata field")
            if not child.is_file() or child.is_symlink():
                raise MetadataError(f"{child}: metadata field must be a regular file")


def validate_metadata(
    source: Path = DEFAULT_SOURCE,
    locale_manifest: Path = DEFAULT_LOCALES,
) -> tuple[str, tuple[str, ...], dict[str, dict[str, str]]]:
    """Validate source and return the fully resolved locale values."""
    source = source.resolve()
    fallback, locales = load_locale_manifest(locale_manifest.resolve())
    _validate_source_shape(source, locales)
    copyright_path = source / "copyright.txt"
    if not copyright_path.is_file():
        raise MetadataError(f"{copyright_path}: required root metadata file is missing")
    copyright_value = _read_text(copyright_path).strip()
    _validate_copyright(copyright_path, copyright_value)

    resolved: dict[str, dict[str, str]] = {}
    for locale in locales:
        locale_values: dict[str, str] = {}
        for field in FIELDS:
            override = source / locale / field.filename
            fallback_path = source / fallback / field.filename
            selected = override if override.is_file() else fallback_path
            if not selected.is_file():
                if field.required:
                    raise MetadataError(
                        f"{source / locale / field.filename}: required field has no {locale} override "
                        f"or {fallback} fallback"
                    )
                continue
            locale_values[field.filename] = _validate_field(selected, field)
        resolved[locale] = locale_values
    return fallback, locales, resolved


def _paths_overlap(first: Path, second: Path) -> bool:
    return first == second or first in second.parents or second in first.parents


def _safe_output(path: Path, source: Path, locale_manifest: Path) -> Path:
    if path.is_symlink():
        raise MetadataError(f"{path}: output must not be a symbolic link")
    resolved = path.resolve()
    safe_root = SAFE_OUTPUT_ROOT.resolve()
    if resolved == safe_root or safe_root not in resolved.parents:
        raise MetadataError(f"{path}: output must be a child of {safe_root}")
    for input_path in (source.resolve(), locale_manifest.resolve()):
        if _paths_overlap(resolved, input_path):
            raise MetadataError(f"{path}: output must not overlap input path {input_path}")
    return resolved


def prepare_metadata(
    output: Path = DEFAULT_OUTPUT,
    source: Path = DEFAULT_SOURCE,
    locale_manifest: Path = DEFAULT_LOCALES,
) -> tuple[Path, int]:
    """Validate and replace a staging tree, removing stale staged files."""
    _, locales, resolved = validate_metadata(source, locale_manifest)
    source = source.resolve()
    output = _safe_output(output, source, locale_manifest)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and not output.is_dir():
        raise MetadataError(f"{output}: existing output is not a directory")
    marker = output / STAGING_MARKER
    if output.exists():
        try:
            marker_content = marker.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            marker_content = ""
        if marker_content != STAGING_MARKER_CONTENT:
            raise MetadataError(
                f"{output}: refusing to replace an unmarked directory; expected {marker}"
            )

    staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    try:
        for name in sorted(ROOT_FILES):
            if (source / name).is_file():
                if name != "copyright.txt":
                    _read_text(source / name)  # an empty category file is an error, like any field
                shutil.copyfile(source / name, staging / name)
        (staging / STAGING_MARKER).write_text(STAGING_MARKER_CONTENT, encoding="utf-8")
        for locale in locales:
            locale_dir = staging / locale
            locale_dir.mkdir()
            for filename, value in resolved[locale].items():
                (locale_dir / filename).write_text(value, encoding="utf-8")
        if output.exists():
            shutil.rmtree(output)
        staging.rename(output)
    except Exception:
        if staging.exists():
            shutil.rmtree(staging)
        raise
    return output, len(locales)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in ("validate", "prepare"):
        subparser = subparsers.add_parser(command)
        subparser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
        subparser.add_argument("--locales", type=Path, default=DEFAULT_LOCALES)
        if command == "prepare":
            subparser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "validate":
            _, locales, _ = validate_metadata(args.source, args.locales)
            print(f"Metadata valid for {len(locales)} App Store locales.")
        else:
            output, count = prepare_metadata(args.output, args.source, args.locales)
            print(f"Prepared {count} App Store locales in {output}")
    except MetadataError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
