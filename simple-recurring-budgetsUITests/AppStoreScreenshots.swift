import XCTest

/// App Store **marketing** screenshot capture for fastlane `snapshot`.
///
/// Captures the 5-shot story (Budgets list → Add Expense → Budget detail → Add/Edit
/// Budget → Settings) across the device/locale matrix in `fastlane/Snapfile`, at the
/// app's **default** Dynamic Type and Light mode, seeding culturally-tuned demo content
/// per locale. This is the marketing counterpart to `LocalizationScreenshotCapture`
/// (which forces `.xxxLarge` for an accessibility check) — do not conflate them.
///
/// **Excluded from every test pipeline.** `scripts/test.sh`, `scripts/test-ui.sh`, and
/// `scripts/test-unit.sh` run an explicit `-only-testing:` allowlist
/// (`AccessibilityAuditTests`, `UserJourneyTests`, `ClearAmountButtonUITests`,
/// `AllocationFirstTapUITests`); this class is deliberately **left off** it, so it never
/// runs in `make test` / `make test-ui` / `make test-unit` / CI — the same
/// exclusion-by-omission that keeps `LocalizationScreenshotCapture` out. Its only runner
/// is the Snapfile `only_testing` invoked by `fastlane screenshots`.
///
/// **Depends on (don't break without updating this):**
/// - Four production `.accessibilityIdentifier` nav handles (locale-invariant):
///   `budget.row.addExpense.accessibilityLabel`, `budgetDetail.menu.accessibilityLabel`,
///   `toolbar.addBudget.accessibilityLabel`, `toolbar.settings.label`.
/// - The `SEED_SCREENSHOTS_JSON` launch-env contract (decoded by `ScreenshotSeed` in the
///   app, DEBUG-only) and the `ScreenshotSeeds/<lang>.json` catalog bundled in this test
///   target, generated by `scripts/screenshot_content/` (skill: `/appstore:screenshot-content`).
/// - `SnapshotHelper.swift` (`setupSnapshot`, `Snapshot.deviceLanguage`, `snapshot(_:)`).
final class AppStoreScreenshots: XCTestCase {
  override func setUpWithError() throws {
    continueAfterFailure = false
  }

  @MainActor func testCaptureAppStoreScreenshots() throws {
    let app = XCUIApplication()
    setupSnapshot(app)

    // `snapshot` sets Snapshot.deviceLanguage from its language cache — the exact runtime
    // code our catalog is keyed by. Falls back to en-US when run outside fastlane.
    let lang = Snapshot.deviceLanguage.isEmpty ? "en-US" : Snapshot.deviceLanguage
    app.launchEnvironment["IS_TESTING"] = "1"
    // Show the Settings iCloud row as "Active" for marketing (the Simulator has no
    // iCloud account). DEBUG-only override, gated on this flag — see SyncStatus.swift.
    app.launchEnvironment["SCREENSHOT_SYNC_OK"] = "1"
    let seed = try XCTUnwrap(
      Self.seedJSON(for: lang),
      "No screenshot seed catalog (ScreenshotSeeds/\(lang).json) bundled for language \(lang)"
    )
    app.launchEnvironment["SEED_SCREENSHOTS_JSON"] = seed

    // 01 — Budgets list (hero): seeded budgets, emoji icons, remaining, carry-over chip.
    app.launch()
    XCTAssertTrue(app.cells.firstMatch.waitForExistence(timeout: 30), "budgets list did not appear")
    snapshot("01_budgets")

    // 02 — Add Expense (fast-logging signature): inline "+" on the first (food) budget row.
    relaunch(app)
    let addExpense = app.buttons["budget.row.addExpense.accessibilityLabel"].firstMatch
    XCTAssertTrue(addExpense.waitForExistence(timeout: 20), "add-expense button not found")
    addExpense.tap()
    _ = app.textFields.firstMatch.waitForExistence(timeout: 15)
    snapshot("02_add_expense")

    // 03 — Budget detail (clarity + carry-over): tap the first budget row.
    relaunch(app)
    XCTAssertTrue(app.cells.firstMatch.waitForExistence(timeout: 20), "budget cell not found")
    app.cells.firstMatch.tap()
    _ = app.buttons["budgetDetail.menu.accessibilityLabel"].waitForExistence(timeout: 15)
    snapshot("03_detail")

    // 04 — Add/Edit Budget (flexible setup): open the sheet, dismiss the auto-keyboard.
    relaunch(app)
    let addBudget = app.buttons["toolbar.addBudget.accessibilityLabel"].firstMatch
    XCTAssertTrue(addBudget.waitForExistence(timeout: 20), "add-budget button not found")
    addBudget.tap()
    _ = app.textFields.firstMatch.waitForExistence(timeout: 15)
    dismissAddBudgetKeyboard(app)
    snapshot("04_add_budget")

    // 05 — Settings.
    relaunch(app)
    let settings = app.buttons["toolbar.settings.label"].firstMatch
    XCTAssertTrue(settings.waitForExistence(timeout: 20), "settings button not found")
    settings.tap()
    _ = app.navigationBars.firstMatch.waitForExistence(timeout: 15)
    snapshot("05_settings")
  }

  // MARK: - Helpers

  /// Relaunch fresh between screens so each shot starts from the seeded budgets list with no
  /// inter-screen navigation state. The launch arguments/environment set on `app` persist.
  @MainActor private func relaunch(_ app: XCUIApplication) {
    app.terminate()
    app.launch()
  }

  /// Dismiss the Add Budget sheet's auto-focused keyboard without dismissing the sheet or
  /// changing state. Tapping the **Daily** period chip (the default selection) ends editing
  /// — the chip's action resigns the keyboard in-app — and re-selecting the already-default
  /// period is a no-op, so the shot deterministically shows Daily with the full form visible.
  @MainActor private func dismissAddBudgetKeyboard(_ app: XCUIApplication) {
    guard app.keyboards.firstMatch.waitForExistence(timeout: 3) else { return }
    let dailyChip = app.buttons["budgetPeriod.daily"].firstMatch
    if dailyChip.waitForExistence(timeout: 5) {
      dailyChip.tap()
    }
    _ = app.keyboards.firstMatch.waitForNonExistence(timeout: 3)
  }

  /// Load the bundled per-locale seed catalog. Synchronized file groups copy resources flat,
  /// so try the subdirectory form first, then the flat form.
  private static func seedJSON(for lang: String) -> String? {
    let bundle = Bundle(for: AppStoreScreenshots.self)
    let candidates = [
      bundle.url(forResource: lang, withExtension: "json", subdirectory: "ScreenshotSeeds"),
      bundle.url(forResource: lang, withExtension: "json"),
    ]
    for case let url? in candidates {
      if let contents = try? String(contentsOf: url, encoding: .utf8) {
        return contents
      }
    }
    return nil
  }
}
